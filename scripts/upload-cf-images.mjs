#!/usr/bin/env node
/**
 * Upload git-backed /public/images files to Cloudflare hosted Images.
 * Writes src/lib/cf-image-ids.ts so the app can serve imagedelivery.net URLs.
 *
 * Hosted Images (not zone /cdn-cgi/image):
 *   POST https://api.cloudflare.com/client/v4/accounts/{account_id}/images/v1
 *
 * Required env:
 *   CLOUDFLARE_API_TOKEN  (Account.Cloudflare Images:Edit)
 *
 * Optional env:
 *   CLOUDFLARE_ACCOUNT_ID (defaults to the Images account for this site)
 *
 * Usage: node scripts/upload-cf-images.mjs
 */

import { readFile, writeFile, readdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const imagesRoot = path.join(root, "public", "images");
const mapFile = path.join(root, "src", "lib", "cf-image-ids.ts");

const ACCOUNT_ID =
  process.env.CLOUDFLARE_ACCOUNT_ID || "2cc579c1ec9e426ed585e933ebf4753b";
const TOKEN = process.env.CLOUDFLARE_API_TOKEN;
const API = `https://api.cloudflare.com/client/v4/accounts/${ACCOUNT_ID}/images/v1`;
const CONCURRENCY = 4;

const IMAGE_EXT = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif", ".gif"]);

function customId(publicPath) {
  return publicPath.replace(/^\//, "").replace(/[^a-zA-Z0-9._-]/g, "-");
}

async function walk(dir, acc = []) {
  const entries = await readdir(dir, { withFileTypes: true });
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      await walk(full, acc);
    } else if (IMAGE_EXT.has(path.extname(entry.name).toLowerCase())) {
      acc.push(full);
    }
  }
  return acc;
}

async function listExisting() {
  const byCustomId = new Map();
  let page = 1;
  while (true) {
    const res = await fetch(`${API}?page=${page}&per_page=100`, {
      headers: { Authorization: `Bearer ${TOKEN}` },
    });
    const json = await res.json();
    if (!json.success) {
      throw new Error(`List failed: ${JSON.stringify(json.errors)}`);
    }
    for (const image of json.result || []) {
      if (image.id) byCustomId.set(image.id, image.id);
    }
    const info = json.result_info || {};
    if (!info.total_pages || page >= info.total_pages) break;
    page += 1;
  }
  return byCustomId;
}

function isDuplicate(errors) {
  return (errors || []).some((e) => {
    const msg = String(e.message || e.code || "");
    return (
      /duplicate/i.test(msg) ||
      e.code === 5409 ||
      e.code === 10009
    );
  });
}

async function upload(filePath) {
  const relative = path
    .relative(path.join(root, "public"), filePath)
    .replace(/\\/g, "/");
  const publicPath = `/${relative}`;
  const id = customId(publicPath);
  const buf = await readFile(filePath);
  const form = new FormData();
  form.append("file", new Blob([buf]), path.basename(filePath));
  form.append("id", id);
  form.append("metadata", JSON.stringify({ gitPath: publicPath }));

  const res = await fetch(API, {
    method: "POST",
    headers: { Authorization: `Bearer ${TOKEN}` },
    body: form,
  });
  const json = await res.json();
  if (!json.success) {
    if (isDuplicate(json.errors)) {
      return { publicPath, id, skipped: true };
    }
    throw new Error(
      `Upload failed for ${publicPath}: ${JSON.stringify(json.errors)}`
    );
  }
  return { publicPath, id: json.result.id || id, skipped: false };
}

async function mapPool(items, limit, worker) {
  const results = new Array(items.length);
  let cursor = 0;
  async function run() {
    while (cursor < items.length) {
      const i = cursor;
      cursor += 1;
      results[i] = await worker(items[i], i);
    }
  }
  await Promise.all(Array.from({ length: Math.min(limit, items.length) }, run));
  return results;
}

async function writeMapping(mapping) {
  const keys = Object.keys(mapping).sort();
  const ordered = {};
  for (const key of keys) ordered[key] = mapping[key];
  const body = `/**
 * Maps git-backed public image paths to Cloudflare Images IDs.
 * Generated by scripts/upload-cf-images.mjs
 */
export const cfImageIds: Record<string, string> = ${JSON.stringify(ordered, null, 2)};
`;
  await writeFile(mapFile, body);
}

async function main() {
  if (!TOKEN) {
    console.error(
      "Set CLOUDFLARE_API_TOKEN (Account.Cloudflare Images:Edit). Git copies in /public/images remain the backup."
    );
    process.exit(1);
  }

  const files = await walk(imagesRoot);
  const existing = await listExisting();
  const mapping = {};

  await mapPool(files, CONCURRENCY, async (file) => {
    const relative = path
      .relative(path.join(root, "public"), file)
      .replace(/\\/g, "/");
    const publicPath = `/${relative}`;
    const id = customId(publicPath);
    if (existing.has(id)) {
      mapping[publicPath] = id;
      console.log(`skip ${publicPath} -> ${id}`);
      return;
    }
    const result = await upload(file);
    mapping[result.publicPath] = result.id;
    console.log(
      `${result.skipped ? "skip" : "ok  "} ${result.publicPath} -> ${result.id}`
    );
  });

  await writeMapping(mapping);
  console.log(`Wrote ${mapFile} (${Object.keys(mapping).length} images)`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
