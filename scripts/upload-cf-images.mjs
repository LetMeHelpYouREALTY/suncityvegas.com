#!/usr/bin/env node
/**
 * Upload git-backed /public/images files to Cloudflare Images.
 * Writes src/lib/cf-image-ids.ts so the app can serve imagedelivery.net URLs.
 *
 * Required env:
 *   CLOUDFLARE_ACCOUNT_ID
 *   CLOUDFLARE_API_TOKEN  (Account.Cloudflare Images:Edit)
 *
 * Usage: node scripts/upload-cf-images.mjs
 */

import { readFile, writeFile, readdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const imagesRoot = path.join(root, "public", "images");
const mapFile = path.join(root, "src", "lib", "cf-image-ids.ts");

const ACCOUNT_ID = process.env.CLOUDFLARE_ACCOUNT_ID;
const TOKEN = process.env.CLOUDFLARE_API_TOKEN;

const IMAGE_EXT = new Set([".jpg", ".jpeg", ".png", ".webp", ".avif", ".gif"]);

async function walk(dir, acc = []) {
  const entries = await readdir(dir, { withFileTypes: true });
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      await walk(full, acc);
    } else if (IMAGE_EXT.has(path.extname(entry.name).toLowerCase())) {
      acc.push(full);
    }
  }
  return acc;
}

async function upload(filePath) {
  const relative = path.relative(path.join(root, "public"), filePath).replace(/\\/g, "/");
  const publicPath = `/${relative}`;
  const customId = publicPath.replace(/^\//, "").replace(/[^a-zA-Z0-9._-]/g, "-");
  const buf = await readFile(filePath);
  const form = new FormData();
  form.append("file", new Blob([buf]), path.basename(filePath));
  form.append("id", customId);
  form.append("metadata", JSON.stringify({ gitPath: publicPath }));

  const res = await fetch(
    `https://api.cloudflare.com/client/v4/accounts/${ACCOUNT_ID}/images/v1`,
    {
      method: "POST",
      headers: { Authorization: `Bearer ${TOKEN}` },
      body: form,
    }
  );
  const json = await res.json();
  if (!json.success) {
    const already = json.errors?.some((e) => String(e.message || "").includes("Duplicate"));
    if (already) {
      return { publicPath, id: customId, skipped: true };
    }
    throw new Error(`Upload failed for ${publicPath}: ${JSON.stringify(json.errors)}`);
  }
  return { publicPath, id: json.result.id, skipped: false };
}

async function main() {
  if (!ACCOUNT_ID || !TOKEN) {
    console.error(
      "Set CLOUDFLARE_ACCOUNT_ID and CLOUDFLARE_API_TOKEN. Git copies in /public/images remain the backup."
    );
    process.exit(1);
  }

  const files = await walk(imagesRoot);
  const mapping = {};
  for (const file of files) {
    const result = await upload(file);
    mapping[result.publicPath] = result.id;
    console.log(`${result.skipped ? "skip" : "ok "} ${result.publicPath} -> ${result.id}`);
  }

  const body = `/**
 * Maps git-backed public image paths to Cloudflare Images IDs.
 * Generated by scripts/upload-cf-images.mjs
 */
export const cfImageIds: Record<string, string> = ${JSON.stringify(mapping, null, 2)};
`;
  await writeFile(mapFile, body);
  console.log(`Wrote ${mapFile}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
